admin.post("/staff", requireRole("superadmin"), (req, res) => {
  const username = (req.body.username || "").trim();
  const password = req.body.password || "";
  const role = req.body.role;

  if (!username || password.length < 8 || !db.STAFF_ROLES.includes(role)) {
    res.redirect("/admin/staff?error=" + encodeURIComponent("Username required, password needs 8+ characters, and role must be valid."));
    return;
  }
  if (db.getStaffUserByUsername(username)) {
    res.redirect("/admin/staff?error=" + encodeURIComponent("That username is already taken."));
    return;
  }

  db.createStaffUser(username, password, role);
  res.redirect("/admin/staff");
});

admin.post("/staff/:id/delete", requireRole("superadmin"), (req, res) => {
  const targetId = parseInt(req.params.id, 10);
  if (targetId === req.staffUser.id) {
    res.redirect("/admin/staff?error=" + encodeURIComponent("You can't remove your own account."));
    return;
  }
  db.deleteStaffUser(targetId);
  res.redirect("/admin/staff");
});

