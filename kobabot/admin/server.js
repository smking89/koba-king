/**
 * GET /api/servers - the real data behind website/src/pages/ServerList.jsx.
 * Public, unauthenticated (the directory itself is public - same as the
 * server-rendered /servers page above), but reflects the requester's own
 * follow state when a session cookie is present. Every field below is a
 * real column, not invented - mirrors admin/serversDirectory.js's
 * serverCard() exactly (same "isLive" telemetry-staleness rule, same
 * dash-worthy fields left null rather than fabricated) so the two
 * renderings of this same data never disagree.
 */
app.get("/api/servers", (req, res) => {
  const entries = db.listDirectoryServers().map((server) => {
    const isLive = server.telemetry_at && Date.now() - server.telemetry_at < TELEMETRY_STALE_MS;
    const rating = db.getDirectoryRating(server.guild_id);
    return {
      raw: server,
      isLive,
      rating,
      server: { isLive, playerCount: server.player_count, queued: server.queued, createdAt: server.created_at },
      flags: { verified: !!server.verified },
    };
  });

  // KOBA Bot Directory Ranking Algorithm (utils/directoryRanking.js) - live
  // population, rating (damped by review count), staff-verified bonus, and
  // a decaying new-listing boost, replacing the old naive "sort by current
  // player count".
  const servers = rankServers(entries).map(({ raw: server, isLive, rating }) => {
    return {
      guildId: server.guild_id,
      title: server.title,
      ownerUsername: server.owner_username || db.getKnownUsername(server.registered_by),
      verified: !!server.verified,
      platforms: server.platforms || [],
      isLive,
      playerCount: isLive ? server.player_count : null,
      maxPlayers: isLive ? server.max_players || null : null,
      queued: isLive ? server.queued : null,
      pingMs: isLive ? server.ping_ms ?? null : null,
      serverCode: server.display_server_id || null,
      kobabotId: server.boombot_id || null,
      mapSizeK: server.map_size ? server.map_size / 1000 : null,
      seed: server.seed || null,
      wipeSchedule: server.wipe_schedule || null,
      rating: { avgStars: rating.avgStars, reviewCount: rating.reviewCount },
      socials: {
        discord: server.invite_url || null,
        tiktok: server.tiktok_url || null,
        twitch: server.twitch_url || null,
        website: server.website_url || null,
      },
      tags: server.tags,
    };
  });
  res.json({ servers });
});

