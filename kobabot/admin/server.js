admin.post("/sales", requireRole("superadmin", "admin"), (req, res) => {
  const { username, amount, plan, note, activate_days } = req.body;
  const discordId = db.findUserIdByUsername(username);
  if (!discordId) {
    return res
      .status(400)
      .send("KOBA Bot doesn't recognize that username yet - it can only resolve usernames it's actually seen (any command, or owning a server it's in).");
  }

  const amountCents = Math.round(parseFloat(amount) * 100);
  if (!Number.isFinite(amountCents) || amountCents < 0) {
    return res.status(400).send("Invalid amount");
  }

  db.recordSale(discordId, amountCents, "USD", plan?.trim() || null, note?.trim() || null, "admin-dashboard");

  if (activate_days) {
    const days = parseInt(activate_days, 10);
    if (Number.isFinite(days) && days > 0) {
      db.setPremiumUser(discordId, Date.now() + days * 24 * 60 * 60 * 1000, "admin-dashboard");
    }
  }

  res.redirect("/admin/sales");
});

